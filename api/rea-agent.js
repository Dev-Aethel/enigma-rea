export default async function handler(req, res) {
  if (req.method !== "POST") {
    return res.status(405).json({ error: "POST required" });
  }

  const { evidence = {}, ciphertext = "" } = req.body || {};
  const cleanLen = ciphertext.replace(/[^A-Za-z]/g, "").length;
  const isM4 = JSON.stringify(evidence).toUpperCase().includes("M4");

  // Built-in deterministic REA hypothesis engine (works out-of-the-box;
  // upgradeable with GEMINI_API_KEY / OPENAI_API_KEY in Vercel env vars)
  const hypothesis = isM4
    ? {
        hypothesis_id: "REA_H2_M4_NAVAL_THETIS",
        rationale: `Detected M4 evidence (${cleanLen} chars). Testing Naval rotors VI-VIII with Gamma wheel and Kriegsmarine weather/position cribs.`,
        proposed_kryptscript: [
          `# Auto-generated by REA Agent`,
          `MODE M4`,
          `CRIB "WETTER" AT 0..20 WEIGHT 15.0`,
          `CRIB "BOOT" AT 0..45 WEIGHT 12.0`,
          `STAGE 1: SWEEP GREEK [GAMMA] ROTORS [VI,VII,VIII] UKW [C-THIN] KEEP 16`,
          `STAGE 2: TUNE RINGS KEEP 4`,
          `STAGE 3: CLIMB PLUGS ITER 1000`
        ].join("\n")
      }
    : {
        hypothesis_id: "REA_H1_M3_BARBAROSSA",
        rationale: `Detected 3-rotor M3 target (${cleanLen} chars). Sweeping Heer rotors I-V on UKW-B.`,
        proposed_kryptscript: [
          `# Auto-generated by REA Agent`,
          `MODE M3`,
          `CRIB "ANGRIFF" AT 0..30 WEIGHT 15.0`,
          `STAGE 1: SWEEP ROTORS [I,II,III,IV,V] UKW [B] KEEP 16`,
          `STAGE 2: TUNE RINGS KEEP 4`,
          `STAGE 3: CLIMB PLUGS ITER 1200`
        ].join("\n")
      };

  return res.status(200).json(hypothesis);
}
